// Run with NODE_PATH pointing to a Playwright installation.
const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1320, height: 960 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.resolve('ui/index.html')).href);
  await page.locator('.card').first().waitFor();
  assert.equal(await page.locator('.card').count(), 6);
  await page.locator('#tabs [data-filter="game"]').click();
  assert.equal(await page.locator('.card').count(), 2);
  await page.locator('#tabs [data-filter="all"]').click();
  await page.locator('#search').fill('Blender');
  assert.equal(await page.locator('.card').count(), 1);
  await page.locator('[data-edit]').click();
  await page.locator('#edit-name').fill('Blender Studio');
  await page.locator('#edit-form button[type="submit"]').click();
  assert.equal(await page.locator('.card h3').textContent(), 'Blender Studio');
  await page.locator('#search').fill('');
  await page.locator('#new-category').click();
  await page.locator('#category-name').fill('Personnel');
  await page.locator('#category-form .primary').click();
  assert.equal(await page.locator('[data-category="Personnel"]').count(), 1);
  await page.locator('[data-edit-category="Personnel"]').click();
  await page.locator('#category-name').fill('Mes outils');
  await page.locator('#category-form .primary').click();
  assert.equal(await page.locator('[data-category="Mes outils"]').count(), 1);
  await page.locator('[data-edit-category="Mes outils"]').click();
  await page.locator('#delete-category').click();
  assert.equal(await page.locator('[data-category="Mes outils"]').count(), 0);
  await page.reload();
  await page.locator('.card').first().waitFor();
  assert.equal(await page.locator('.card h3').first().textContent(), 'Blender Studio');
  await page.locator('.card').first().locator('[data-edit]').click();
  await page.locator('#visibility').click();
  assert.equal(await page.locator('.card').count(), 5);
  await page.locator('[data-filter="hidden"]').click();
  assert.equal(await page.locator('.card').count(), 1);
  await page.reload();
  await page.locator('.card').first().waitFor();
  assert.equal(await page.locator('.card').count(), 5);
  await page.locator('[data-filter="hidden"]').click();
  await page.locator('[data-edit]').click();
  await page.locator('#visibility').click();
  assert.equal(await page.locator('.card').count(), 0);
  await page.locator('#tabs [data-filter="all"]').click();
  assert.equal(await page.locator('.card').count(), 6);
  await page.locator('#theme').selectOption('light');
  assert.equal(await page.locator('body.light').count(), 1);
  await page.locator('#list-view').click();
  assert.equal(await page.locator('#apps.list').count(), 1);
  await page.locator('#grid-view').click();
  await page.locator('#theme').selectOption('dark');
  await page.screenshot({ path: 'ui-preview.png', fullPage: true });
  assert.deepEqual(errors, []);
  await browser.close(); console.log('UI verified: filters, search, edit, categories, themes, views.');
})().catch(error => { console.error(error); process.exitCode = 1; });
